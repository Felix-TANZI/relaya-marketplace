/** Applique les fiches détaillées au catalogue (produits sans fiche : inchangés). */
export function avecFiches(c: Record<string, Produit>): Record<string, Produit> {
  return Object.fromEntries(Object.entries(c).map(([id, p]) => [id, FICHES_PRODUITS[id] ? { ...p, ...FICHES_PRODUITS[id] } : p]))
}
